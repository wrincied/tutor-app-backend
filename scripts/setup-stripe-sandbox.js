/**
 * Stripe Test Mode bootstrap for Simple4U Pro.
 *
 * Usage:
 *   1. Put sk_test_... into backend/.env as STRIPE_SECRET_KEY
 *   2. node scripts/setup-stripe-sandbox.js
 *   3. Optional: node scripts/setup-stripe-sandbox.js --write   (appends price IDs to .env)
 *   4. Restart backend. Webhook locally:
 *        stripe listen --forward-to localhost:3001/api/billing/webhook
 */
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });

const WRITE = process.argv.includes('--write');

function fail(message) {
  console.error(`\n❌ ${message}\n`);
  process.exit(1);
}

async function main() {
  const key = String(process.env.STRIPE_SECRET_KEY || '').trim();
  if (!key || key === 'your_stripe_secret_key' || !key.startsWith('sk_')) {
    fail(
      'Set a real Stripe secret in backend/.env:\n' +
        '  STRIPE_SECRET_KEY=sk_test_...\n' +
        'Get it from: https://dashboard.stripe.com/test/apikeys',
    );
  }
  if (!key.startsWith('sk_test_')) {
    fail(
      'Sandbox setup requires a TEST key (sk_test_...). ' +
        'Switch Stripe Dashboard to Test mode, then copy the Secret key.',
    );
  }

  // eslint-disable-next-line global-require
  const stripe = require('stripe')(key);

  const account = await stripe.accounts.retrieve();
  console.log(`✓ Stripe Test mode OK (account ${account.id})`);

  let product = null;
  try {
    const existing = await stripe.products.search({
      query: "name:'Simple4U Pro' AND active:'true'",
      limit: 1,
    });
    product = existing.data[0] || null;
  } catch {
    const listed = await stripe.products.list({ active: true, limit: 100 });
    product = listed.data.find((p) => p.name === 'Simple4U Pro') || null;
  }
  if (product) {
    console.log(`✓ Reusing product ${product.id}`);
    if (!product.tax_code) {
      product = await stripe.products.update(product.id, {
        tax_code: 'txcd_10000000',
      });
      console.log(`✓ Set tax_code on product ${product.id}`);
    }
  } else {
    product = await stripe.products.create({
      name: 'Simple4U Pro',
      description: 'Simple4U Pro subscription (sandbox)',
      // SaaS / electronically supplied services
      tax_code: 'txcd_10000000',
      metadata: { app: 'simple4u', env: 'test' },
    });
    console.log(`✓ Created product ${product.id}`);
  }

  async function ensurePrice({ nickname, unitAmount, currency, interval }) {
    const prices = await stripe.prices.list({
      product: product.id,
      active: true,
      limit: 100,
    });
    const found = prices.data.find(
      (p) =>
        p.nickname === nickname ||
        (p.unit_amount === unitAmount &&
          p.currency === currency &&
          p.recurring?.interval === interval),
    );
    if (found) {
      console.log(`✓ Reusing price ${nickname}: ${found.id}`);
      return found;
    }
    const created = await stripe.prices.create({
      product: product.id,
      currency,
      unit_amount: unitAmount,
      nickname,
      recurring: { interval },
      metadata: { app: 'simple4u', env: 'test', interval },
    });
    console.log(`✓ Created price ${nickname}: ${created.id}`);
    return created;
  }

  // Matches frontend/backend subscription-pricing defaults for AT (EUR).
  const monthly = await ensurePrice({
    nickname: 'simple4u_pro_monthly_eur',
    unitAmount: 999,
    currency: 'eur',
    interval: 'month',
  });
  const yearly = await ensurePrice({
    nickname: 'simple4u_pro_yearly_eur',
    unitAmount: 9999,
    currency: 'eur',
    interval: 'year',
  });
  const earlyYearly = await ensurePrice({
    nickname: 'simple4u_pro_early_yearly_eur',
    unitAmount: 5999,
    currency: 'eur',
    interval: 'year',
  });

  let referralCoupon = null;
  const coupons = await stripe.coupons.list({ limit: 100 });
  referralCoupon = coupons.data.find((c) => c.id === 'simple4u_referral_20' || c.name === 'Simple4U referral 20%') || null;
  if (!referralCoupon) {
    referralCoupon = await stripe.coupons.create({
      id: 'simple4u_referral_20',
      name: 'Simple4U referral 20%',
      percent_off: 20,
      duration: 'once',
      metadata: { app: 'simple4u', kind: 'referral' },
    });
    console.log(`✓ Created coupon ${referralCoupon.id}`);
  } else {
    console.log(`✓ Reusing coupon ${referralCoupon.id}`);
  }

  const block = [
    '',
    '# --- Stripe Test Mode (sandbox) — generated by setup-stripe-sandbox.js ---',
    `STRIPE_SECRET_KEY=${key}`,
    `STRIPE_PRICE_ID_PRO=${monthly.id}`,
    `STRIPE_PRICE_ID_PRO_MONTHLY=${monthly.id}`,
    `STRIPE_PRICE_ID_PRO_YEARLY=${yearly.id}`,
    `STRIPE_PRICE_ID_PRO_EARLY_YEARLY=${earlyYearly.id}`,
    `STRIPE_COUPON_REFERRAL_20=${referralCoupon.id}`,
    '# STRIPE_WEBHOOK_SECRET=whsec_...  # from: stripe listen --forward-to localhost:3001/api/billing/webhook',
    '',
  ].join('\n');

  console.log('\nAdd these to backend/.env:\n');
  console.log(block);

  if (WRITE) {
    const fs = require('fs');
    const envPath = path.join(__dirname, '..', '.env');
    let envText = fs.readFileSync(envPath, 'utf8');
    const upsert = (name, value) => {
      const re = new RegExp(`^${name}=.*$`, 'm');
      if (re.test(envText)) {
        envText = envText.replace(re, `${name}=${value}`);
      } else {
        envText += `\n${name}=${value}`;
      }
    };
    upsert('STRIPE_SECRET_KEY', key);
    upsert('STRIPE_PRICE_ID_PRO', monthly.id);
    upsert('STRIPE_PRICE_ID_PRO_YEARLY', yearly.id);
    upsert('STRIPE_PRICE_ID_PRO_EARLY_YEARLY', earlyYearly.id);
    upsert('STRIPE_COUPON_REFERRAL_20', referralCoupon.id);
    if (!/^STRIPE_PRICE_ID_PRO_MONTHLY=/m.test(envText)) {
      envText += `\nSTRIPE_PRICE_ID_PRO_MONTHLY=${monthly.id}`;
    } else {
      upsert('STRIPE_PRICE_ID_PRO_MONTHLY', monthly.id);
    }
    fs.writeFileSync(envPath, envText.endsWith('\n') ? envText : `${envText}\n`);
    console.log(`✓ Wrote price IDs into ${envPath}`);
  }

  console.log('Next:');
  console.log('  1. Restart backend (node backend/server.js)');
  console.log('  2. Optional webhook: stripe listen --forward-to localhost:3001/api/billing/webhook');
  console.log('  3. Pay with test card 4242 4242 4242 4242');
  console.log('');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
